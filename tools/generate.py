#!/usr/bin/env python3
"""Generate src/sets/*.rs from the upstream icon packages.

Usage:
    npm pack lucide-static @material-design-icons/svg
    mkdir lucide material
    tar xzf lucide-static-*.tgz -C lucide
    tar xzf material-design-icons-svg-*.tgz -C material
    python3 tools/generate.py lucide/package material/package

Every shape (circle, rect, line, ...) is converted to SVG path data so the
crate only needs one path parser.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAX_TAGS = 6


def num(v):
    v = float(v)
    return ("%.3f" % v).rstrip("0").rstrip(".") if v != int(v) else str(int(v))


def to_path(tag, a):
    g = lambda k, d=0: float(a.get(k, d))
    if tag == "path":
        return a["d"]
    if tag == "circle" or tag == "ellipse":
        cx, cy = g("cx"), g("cy")
        rx = g("r") if tag == "circle" else g("rx")
        ry = g("r") if tag == "circle" else g("ry")
        return (f"M{num(cx - rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0"
                f"a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0z")
    if tag == "rect":
        x, y, w, h = g("x"), g("y"), g("width"), g("height")
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx == 0:
            return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
        return (f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(ry)}"
                f"v{num(h - 2 * ry)}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(ry)}"
                f"h{num(-(w - 2 * rx))}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(-ry)}"
                f"v{num(-(h - 2 * ry))}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(-ry)}z")
    if tag == "line":
        return f"M{num(g('x1'))} {num(g('y1'))}L{num(g('x2'))} {num(g('y2'))}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{num(pts[i])} {num(pts[i + 1])}" for i in range(0, len(pts) - 1, 2)]
        return "M" + "L".join(pairs) + ("z" if tag == "polygon" else "")
    raise ValueError(f"unsupported element {tag}")


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_set(path, doc, entries):
    lines = [
        "// @generated by tools/generate.py. Do not edit by hand.",
        f"//! {doc}",
        "",
        "use crate::IconData;",
        "",
        "#[rustfmt::skip]",
        "pub(crate) static ICONS: &[IconData] = &[",
    ]
    for name, paths, tags in sorted(entries):
        p = ", ".join(rust_str(d) for d in paths)
        t = ", ".join(rust_str(x) for x in tags)
        lines.append(f"    IconData {{ name: {rust_str(name)}, paths: &[{p}], tags: &[{t}] }},")
    lines.append("];")
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} icons to {path.relative_to(ROOT)}")


def svg_elements(text):
    """(tag, attrs) for every drawable element in an SVG file."""
    out = []
    for tag, raw in re.findall(r"<(path|circle|rect|ellipse|polygon|polyline|line)\s([^>]*?)/?>", text):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', raw))
        if attrs.get("fill") == "none" and tag == "path" and attrs.get("d") in ("M0 0h24v24H0z", "M0 0h24v24H0V0z"):
            continue
        out.append((tag, attrs))
    return out


def lucide(pkg):
    tags = json.loads((pkg / "tags.json").read_text())
    version = json.loads((pkg / "package.json").read_text())["version"]
    entries = []
    for svg in sorted((pkg / "icons").glob("*.svg")):
        paths = [to_path(tag, attrs) for tag, attrs in svg_elements(svg.read_text())]
        if paths:
            entries.append((svg.stem, paths, tags.get(svg.stem, [])[:MAX_TAGS]))
    write_set(ROOT / "src/sets/lucide.rs",
              f"Lucide {version} (ISC): stroked outline icons on a 24x24 grid.", entries)
    (ROOT / "licenses/LUCIDE-ISC.txt").write_text((pkg / "LICENSE").read_text())


def material(pkg):
    version = json.loads((pkg / "package.json").read_text())["version"]
    entries = []
    for svg in sorted((pkg / "filled").glob("*.svg")):
        text = svg.read_text()
        ds = [to_path(tag, attrs) for tag, attrs in svg_elements(text)
              if attrs.get("fill") != "none"]
        if ds:
            entries.append((svg.stem.replace("_", "-"), ds, []))
    write_set(ROOT / "src/sets/material.rs",
              f"Material Icons {version} (Apache-2.0), filled style, on a 24x24 grid.", entries)
    (ROOT / "licenses/MATERIAL-APACHE-2.0.txt").write_text((pkg / "LICENSE").read_text())


if __name__ == "__main__":
    lucide(pathlib.Path(sys.argv[1]))
    material(pathlib.Path(sys.argv[2]))
